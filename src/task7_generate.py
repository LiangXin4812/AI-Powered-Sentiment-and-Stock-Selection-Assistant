def generate_and_store(engine, ticker, report_date,
                       groq_api_key=None, store=True, verbose=True):
    """
    One (ticker, date) → one report row.

    groq_api_key=None forces the deterministic path — usable today with no
    quota. With a key, Prompt A runs first and any compliance failure falls
    back automatically.
    """
    inp = build_report_input(engine, ticker, report_date)

    if inp is not None and inp.get("status") == "complete":
        # System-level walk-forward record (all 15 stocks, trailing 30 days).
        # Injected into inp BEFORE section rendering and validation so (a) the
        # reliability section can quote substantiated aggregate statistics
        # even while per-stock history is gated, and (b) R5's number whitelist
        # picks the figures up automatically.
        try:
            with engine.connect() as conn:
                row = conn.execute(text("""
                    SELECT COUNT(*),
                           AVG(CASE WHEN predicted_class = actual_class
                                    THEN 1.0 ELSE 0.0 END)
                    FROM task6_predictions
                    WHERE is_champion = TRUE
                      AND actual_class IS NOT NULL
                      AND forecast_target <= CAST(:d AS DATE)
                      AND prediction_date <  CAST(:d AS DATE)
                      AND prediction_date >= CAST(:d AS DATE) - 30
                """), {"d": str(report_date)}).fetchone()
            if row and row[0]:
                inp["reliability"]["system"] = {
                    "n": int(row[0]),
                    "accuracy": float(row[1]) if row[1] is not None else None,
                    "window_days": 30,
                }
        except Exception:
            pass   # aggregate stats are an enrichment, never a blocker

    if inp is None:
        if verbose:
            print(f"  {ticker:<10} no T5 row — skipped")
        return None

    if inp.get("status") != "complete":
        if verbose:
            print(f"  {ticker:<10} incomplete ({inp.get('missing')})")
        if store:
            stub_sections = {"notice": f"Data incomplete: {inp.get('missing')} "
                                       f"missing for this date."}
            stub_text = (f"{ticker} · {report_date}\n"
                         f"Report incomplete — {inp.get('missing')} missing.\n\n"
                         f"{DISCLAIMER}")
            store_report(engine, inp, stub_sections, stub_text, None,
                         "incomplete", True, [], PROMPT_VERSION_FALLBACK)
        return {"status": "incomplete"}

    attribution = fetch_attribution(engine, ticker, report_date)

    mode, sections, pver, flags = "fallback", None, PROMPT_VERSION_FALLBACK, []

    if groq_api_key:
        llm_sections, pver_llm, err = generate_llm_sections(
            inp, attribution, groq_api_key)
        if llm_sections is not None:
            # Merge over the deterministic base so key_evidence and
            # methodology are always present regardless of path.
            merged = render_fallback(inp, attribution)
            merged.update(llm_sections)
            ok, flags = validate_compliance(merged, inp, attribution)
            if ok:
                sections, mode, pver = merged, "llm", pver_llm
            else:
                if verbose:
                    print(f"  {ticker:<10} compliance failed "
                          f"({len(flags)} flag(s)) — falling back")
        else:
            if verbose:
                print(f"  {ticker:<10} LLM failed ({err}) — falling back")

    if sections is None:
        sections = render_fallback(inp, attribution)
        # The renderer is built to pass, but it is checked like any draft. A
        # failure here means a template or input problem: the stock's report
        # is blocked rather than published, and the flags are stored.
        _, fb_flags = validate_compliance(sections, inp, attribution)
        if fb_flags:
            if verbose:
                print(f"  {ticker:<10} ⚠️ deterministic text failed {fb_flags}; report blocked")
            flags, mode = fb_flags, "blocked"
            sections = {"notice": "Report withheld: the generated text failed a "
                                  "compliance check and is under review."}

    full_text = render_full_text(inp, sections, attribution, mode)

    if store:
        store_report(engine, inp, sections, full_text, attribution,
                     mode, len(flags) == 0, flags, pver)

    if verbose:
        print(f"  {ticker:<10} {inp['fusion']['archetype']:<14} "
              f"[{inp['attention']['level']}]  mode={mode}")

    return {"input": inp, "sections": sections, "full_text": full_text,
            "mode": mode, "attribution": attribution,
            "status": "blocked" if mode == "blocked" else "complete"}


def generate_daily_batch(engine, report_date, tickers,
                         groq_api_key=None, store=True):
    """All stocks for one date, ELEVATED summary first."""
    ensure_table(engine)
    print(f"\n{'='*67}\nTASK 7 REPORTS — {report_date}\n{'='*67}")

    results = {}
    for tkr in tickers:
        r = generate_and_store(engine, tkr, report_date,
                               groq_api_key=groq_api_key, store=store)
        if r and "input" in r:
            results[tkr] = r

    elevated = [t for t, r in results.items()
                if r["input"]["attention"]["level"] == "ELEVATED"]
    notable  = [t for t, r in results.items()
                if r["input"]["attention"]["level"] == "NOTABLE"]

    print(f"\n  {len(results)} reports generated")
    print(f"  ELEVATED: {elevated if elevated else 'none'}")
    print(f"  NOTABLE:  {notable if notable else 'none'}")
    print(f"  Everything else is routine.")
    return results
