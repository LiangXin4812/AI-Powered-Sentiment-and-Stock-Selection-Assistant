"""
task7_generate.py — report generation, compliance validation, storage

Sits on top of task7_report.py. That module decides (archetype, attention,
reliability); this one renders those decisions into a reader-facing report,
checks the result against compliance rules, and stores it.

TWO GENERATION PATHS
--------------------
llm       Prompt A (external YAML) asks the LLM to phrase the structured
          input. Output is validated; any violation falls through to the
          deterministic path. Requires a Groq key and quota.

fallback  Pure templates filled with the same numbers. No LLM, no quota,
          always compliant by construction. This is also the degraded mode
          when Prompt A output fails validation — the user gets a dry report,
          never a broken one.

COMPLIANCE (Prompt B, v1 = deterministic)
-----------------------------------------
The July design sketched Prompt B as a second LLM pass. v1 implements the
rules as code instead: regex + structural checks are reproducible, auditable,
and free — properties a compliance layer should have before subtlety. An LLM
second pass can be layered on later for tone; the hard rules live here.

  R1  no advice verbs directed at the reader
  R2  no price targets
  R3  no certainty language about future prices
  R4  weak reliability must be stated, not hidden
  R5  every number in the text must exist in the input data
  R6  divergence patterns must admit the cause is undetermined
  R7  disclaimer present (guaranteed: appended outside the LLM)

STORAGE
-------
final_reports is append-only. Re-generating the same (ticker, date) inserts a
new row rather than overwriting — the same historical-marker principle as
task6_predictions.is_champion. Readers take the latest row per (ticker, date).
"""

