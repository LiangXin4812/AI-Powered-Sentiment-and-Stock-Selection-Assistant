def load_prompt_a(yaml_path=None):
    """Return the reviewed external prompt and its version; fail on missing YAML."""
    import yaml
    yaml_path = yaml_path or DEFAULT_YAML_PATH
    with open(yaml_path) as f:
        doc = yaml.safe_load(f)
    return doc["prompt_a"]["template"], doc["prompt_a"].get("version", "yaml")


