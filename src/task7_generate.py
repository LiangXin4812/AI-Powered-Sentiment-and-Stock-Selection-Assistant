def _pct(x, dp=1):
    return f"{x * 100:.{dp}f}%" if x is not None else "n/a"


def _fmt_prob(p):
    """Guideline: no false precision. Calibrated probabilities at this sample
    size are not distinguishable near the extremes, so anything past 0.99 is
    shown as a bound, not a value."""
    if p is None:
        return "n/a"
    if p > 0.99:
        return ">0.99"
    if p < 0.01:
        return "<0.01"
    return f"{p:.2f}"


# Guideline §6 control: "automatically suppress outputs when thresholds are
# breached". A stock whose champion model has run more than 5 points below
# its own naive baseline has its directional forecast withheld from the
# report. The raw prediction stays in task6_predictions for audit.
SUPPRESS_EDGE = -0.05


def _is_suppressed(inp):
    edge = (inp.get("reliability") or {}).get("t6_edge")
    return edge is not None and edge < SUPPRESS_EDGE


