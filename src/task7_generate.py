# SOURCE ATTRIBUTION — from the audit trail
#
# llm_analyses stores the finished analysis; the full per-rule feature list
# (with source tags) lives in llm_analyses_audit.features_result. Latest audit
# row wins when a (ticker, date) was re-run.
# ═══════════════════════════════════════════════════════════════════════════

def fetch_attribution(engine, ticker, report_date):
    with engine.connect() as conn:
        row = conn.execute(text("""
            SELECT features_result
            FROM llm_analyses_audit
            WHERE ticker = :t AND analysis_date::date = CAST(:d AS DATE)
            ORDER BY id DESC
            LIMIT 1
        """), {"t": ticker, "d": str(report_date)}).fetchone()

    if row is None or row[0] is None:
        return None

    fr = row[0] if isinstance(row[0], dict) else json.loads(row[0])
    features = fr.get("features", [])
    if not features:
        return None
    att = attribute_sources(features)
    att["rule_layer_version"] = fr.get("_rule_layer_version")
    # The fired rules themselves, as the rule layer computed them. These are
    # the deterministic evidence the report cites; the LLM-written
    # key_drivers are not used for figures (see _sec_key_evidence).
    att["features"] = [
        {"factor":    f.get("factor", "?"),
         "direction": f.get("direction"),
         "weight":    float(f.get("baseline_weight", 0.0)),
         "source":    f.get("source", "?"),
         "decisive":  bool(f.get("flips_call"))}
        for f in features
    ]
    att["net_score"] = (fr.get("score_breakdown") or {}).get("net_score")
    # Side totals, so a neutral reading can be explained as "up X vs down Y"
    # instead of naming a source whose rules cancel out.
    att["up_total"] = round(sum(f["weight"] for f in att["features"]
                                if f["direction"] == "bullish"), 3)
    att["down_total"] = round(sum(f["weight"] for f in att["features"]
                                  if f["direction"] != "bullish"), 3)
    return att


