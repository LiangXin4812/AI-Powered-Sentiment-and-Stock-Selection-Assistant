def render_full_text(inp, sections, attribution, mode):
    """Assemble the display text. Disclaimer is appended here, outside any
    LLM output, so rule R7 holds by construction on every path."""
    lines = []
    lines.append("═" * 67)
    lines.append(f"{inp['ticker']}")
    lines.append(f"Daily Signal Digest · data as of {inp['report_date']} "
                 f"market close · report generated {inp['generated_at'][:16]} SGT")
    lines.append(f"Attention level: {inp['attention']['level']}")
    if inp.get("actual", {}).get("matured"):
        lines.append("Retrospective: the outcome section uses prices from "
                     "after the report date. All other figures use only "
                     "information available at that date.")
    lines.append("═" * 67)

    if mode == "blocked":
        lines += ["", sections.get("notice", "Report withheld."), "", "─" * 67,
                  DISCLAIMER, "═" * 67]
        return "\n".join(lines)

    if inp["attention"]["level"] == "ROUTINE" and \
            inp["fusion"]["archetype"] in LOW_INFORMATION_ARCHETYPES:
        lines.append("")
        lines.append("Nothing today requires your attention on this stock.")

    for key in SECTION_ORDER:
        lines.append("")
        lines.append(SECTION_TITLES[key])
        lines.append(sections[key])

    lines.append("")
    lines.append("─" * 67)
    lines.append(DISCLAIMER)
    lines.append("")
    lines.append(f"Sources: Task 5 evidence assessment (llm_analyses, "
                 f"{inp['report_date']}), Task 6 forecast (task6_predictions, "
                 f"{inp['t6']['champion_model']}), yfinance close prices. "
                 f"Generation mode: {mode}.")
    lines.append("═" * 67)
    return "\n".join(lines)


# ═══════════════════════════════════════════════════════════════════════════
# COMPLIANCE VALIDATION (Prompt B v1 — deterministic)
# ═══════════════════════════════════════════════════════════════════════════

# R1: advice verbs aimed at the reader. Word-boundary patterns chosen to
# avoid corporate-name false positives ("Keppel Corporation Holdings",
# "shareholding"), which a naive \bhold\b would hit.
_R1_PATTERNS = [
    r"\byou should\b", r"\bwe recommend\b", r"\brecommended?\b",
    r"\bbuy\b", r"\bsell\b", r"\baccumulate\b",
    r"\b(?<!share)(?<!stock)hold\b(?!ing)",
    r"\bavoid the stock\b", r"\btake profit\b", r"\bcut loss(es)?\b",
    r"\bgood (time|opportunity) to\b", r"\badd to (your )?position\b",
]

# R2: price targets
_R2_PATTERNS = [
    r"price target", r"target price", r"\btarget of\b",
    r"(?:S\$|\$|SGD)\s?\d+(?:\.\d+)?\s*(?:target|by\b)",
    r"\bwill (?:reach|hit|touch)\b",
]

# R3: certainty about future prices
_R3_PATTERNS = [
    r"\bwill (?:rise|fall|drop|rally|climb|decline|go (?:up|down))\b",
    r"\bguaranteed\b", r"\bcertain(?:ly)? (?:to|will)\b",
    r"\bis going to (?:rise|fall|drop|rally)\b",
]

# Lookarounds keep digits inside identifiers (BN4, F34, rl_v7) from being
# read as standalone numbers.
_NUM_RE = re.compile(r"(?<![A-Za-z0-9])[-+]?\d+(?:\.\d+)?%?(?![A-Za-z0-9])")


def _collect_numbers(obj, plain, pct):
    """
    Harvest numeric values into two whitelists.

    plain — raw values and their roundings. What a bare number in the text
            may match.
    pct   — additionally includes value×100. Only tokens written WITH a
            percent sign may use this, so 0.45 (an accuracy) can appear as
            "45%" but cannot launder an unrelated bare "45" (a price).
    """
    if isinstance(obj, bool) or obj is None:
        return
    if isinstance(obj, (int, float)):
        v = float(obj)
        if v != v or v in (float("inf"), float("-inf")):    # NaN / inf: not a quotable number
            return
        for cand in (v, round(v), round(v, 1), round(v, 2),
                     abs(v), round(abs(v)), round(abs(v), 1), round(abs(v), 2)):
            plain.add(round(cand, 2))
            pct.add(round(cand, 2))
        for cand in (v * 100, round(v * 100), round(v * 100, 1),
                     abs(v) * 100, round(abs(v) * 100), round(abs(v) * 100, 1)):
            pct.add(round(cand, 2))
    elif isinstance(obj, dict):
        for x in obj.values():
            _collect_numbers(x, plain, pct)
    elif isinstance(obj, (list, tuple)):
        for x in obj:
            _collect_numbers(x, plain, pct)


def validate_compliance(sections, inp, attribution):
    """
    Returns (passed, flags). Checks R1-R6 on the LLM's sections; R7 is
    guaranteed by render_full_text. Any flag → caller falls back.
    """
    flags = []
    body = " ".join(str(v) for v in sections.values()).lower()

    for pat in _R1_PATTERNS:
        if re.search(pat, body):
            flags.append(f"R1 advice language: /{pat}/")
    for pat in _R2_PATTERNS:
        if re.search(pat, body):
            flags.append(f"R2 price target: /{pat}/")
    for pat in _R3_PATTERNS:
        if re.search(pat, body):
            flags.append(f"R3 certainty language: /{pat}/")

    # R4 — weak reliability must be admitted
    verdict = inp["reliability"]["verdict"]
    if verdict in ("insufficient", "below"):
        rel_text = str(sections.get("reliability", "")).lower()
        admits = any(w in rel_text for w in
                     ("limited", "not enough", "insufficient", "below",
                      "treat this", "weigh", "lightly", "caution",
                      "withheld", "withholds"))
        if not admits:
            flags.append(f"R4 reliability verdict '{verdict}' not admitted in text")

    # R5 — every number in the text exists in the input.
    # Percent-suffixed tokens may match the ×100 expansion of an input value;
    # bare numbers may not, so an accuracy of 0.45 cannot launder a "$45".
    allowed_plain, allowed_pct = set(), set()
    _collect_numbers(inp, allowed_plain, allowed_pct)
    _collect_numbers(attribution or {}, allowed_plain, allowed_pct)
    small_ints = {1, 2, 3, 4, 5, 7, 14, 15, 20, 30}  # day/stock counts the
    allowed_plain |= small_ints                       # text may name
    allowed_pct   |= small_ints
    # 0.99 appears as the display bound ">0.99" (false-precision guard) even
    # when the underlying value is 0.995+; whitelist the bound itself.
    allowed_plain.add(0.99); allowed_pct.add(0.99)
    # The rule layer's decision line, quoted in the evidence section.
    allowed_plain.add(0.35); allowed_pct.add(0.35)
    allowed_plain.add(0.01); allowed_pct.add(0.01)
    # Calendar dates (report date, champion-since date) are identifiers, not
    # quantities; remove them before scanning or "2026-09-13" reads as three
    # invented numbers.
    for tok in _NUM_RE.findall(re.sub(r"\d{4}-\d{2}-\d{2}", " ", body)):
        is_pct = tok.endswith("%")
        # Magnitude comparison: the whitelist stores absolute forms, and a
        # sign flip (threshold lower bound -1.09%, SHAP -0.429 for a stored
        # weight 0.429) is direction, not invention. A fabricated magnitude
        # is still caught either way.
        val = round(abs(float(tok.rstrip("%"))), 2)
        pool = allowed_pct if is_pct else allowed_plain
        if val not in pool and val > 0.01:
            flags.append(f"R5 number not in input data: {tok}")

    # R6 — divergence must admit undetermined cause
    # When the forecast is suppressed the report shows no model divergence to
    # explain, so R6 does not apply.
    if inp["fusion"]["archetype"] in DIVERGENCE_ARCHETYPES and not _is_suppressed(inp):
        fit_text = str(sections.get("how_these_fit", "")).lower()
        admits = any(p in fit_text for p in
                     ("cannot determine", "cannot tell", "can't determine",
                      "unable to determine", "not possible to determine",
                      "cannot say which", "cannot know which"))
        if not admits:
            flags.append("R6 divergence without undetermined-cause statement")

    return len(flags) == 0, flags


# ═══════════════════════════════════════════════════════════════════════════
# LLM PATH
# ═══════════════════════════════════════════════════════════════════════════

def generate_llm_sections(inp, attribution, groq_api_key,
                          model=None, yaml_path=None):
    """
    Prompt A → sections dict, or (None, version, error) on any failure.
    Caller decides whether to fall back.
    """
    import requests, time

    settings = globals().get("LLM_SETTINGS")
    if not settings:
        return None, "unconfigured", "LLM settings were not loaded"
    model = model or settings["model"]
    try:
        template, version = load_prompt_a(yaml_path)
    except Exception as exc:
        return None, "prompt-unavailable", f"Prompt configuration: {type(exc).__name__}"
    prompt = (template
              .replace("{data_json}", json.dumps(inp, indent=1, default=str))
              .replace("{attribution_json}",
                       json.dumps(attribution or {}, indent=1, default=str)))

    err = "Rate limit retries exhausted"
    for attempt in range(settings["max_retries"]):
        try:
            resp = requests.post(
                settings["endpoint"],
                headers={"Authorization": f"Bearer {groq_api_key}"},
                json={"model": model,
                      "messages": [{"role": "user", "content": prompt}],
                      "temperature": settings["temperature"],
                      "max_tokens": settings["max_tokens"]["t7"]},
                timeout=settings["timeout_s"],
            )
            if resp.status_code == 429:
                time.sleep(settings["backoff_base_s"] *
                           settings["backoff_factor"] ** attempt)
                continue
            resp.raise_for_status()
            raw = resp.json()["choices"][0]["message"]["content"].strip()
            raw = re.sub(r"^```(?:json)?|```$", "", raw, flags=re.M).strip()
            sections = json.loads(raw)
            missing = [k for k in LLM_REQUIRED_KEYS + ["one_liner"]
                       if k not in sections]
            if missing:
                return None, version, f"missing keys: {missing}"
            return sections, version, None
        except Exception as e:
            err = f"{type(e).__name__}: {e}"
    return None, version, err


