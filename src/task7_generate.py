def _sec_today_signals(inp, attribution):
    t5 = inp["t5"]
    s = t5["sentiment"]
    lead = {"bullish": "leaned positive", "bearish": "leaned negative",
            "neutral": "showed no clear lean"}[s]
    txt = f"Today's combined signal reading {lead}"
    # Name the driver by NET push in the direction of the call, not by gross
    # weight. (19 Sep fix: D05 said "driven mainly by Political signals (43%)"
    # although Political rules cancelled out, +0.250 vs -0.242; the lean
    # actually came from News.) Gross share is still shown for context.
    bs = (attribution or {}).get("by_source") or {}
    if bs and s in ("bullish", "bearish"):
        sign = 1 if s == "bullish" else -1
        drv = max(bs, key=lambda k: sign * bs[k]["net"])
        if sign * bs[drv]["net"] > 0:
            txt += (f", driven mainly by {drv} signals (net "
                    f"{bs[drv]['net']:+.3f} toward this lean)")
        dom = attribution.get("dominant")
        if dom and dom != drv and abs(bs[dom]["net"]) < 0.5 * bs[dom]["weight"]:
            txt += (f". {dom} signals carried the most gross weight "
                    f"({bs[dom]['share']:.0%}) but largely offset each other")
    elif (attribution or {}).get("net_score") is not None and \
            attribution.get("up_total") is not None:
        txt += (f": rules pointing up added {attribution['up_total']:.3f} and "
                f"rules pointing down {attribution['down_total']:.3f}, a net of "
                f"{attribution['net_score']:+.3f}, inside the band where no lean "
                f"is called")
    elif bs and attribution.get("dominant"):
        dom = attribution["dominant"]
        txt += (f"; the largest source by weight was {dom} "
                f"({bs[dom]['share']:.0%} of the reading's weight)")
    txt += (f". Internal evidence strength was {t5['confidence']:.2f}; "
            "this rule score is not a calibrated probability of a future rise")
    if t5.get("warning_level") == "high":
        txt += (", though the system flagged strong internal tension between "
                "its own components")
    elif t5.get("warning_level") == "mild":
        txt += ", with some internal tension noted"
    txt += "."
    if attribution and attribution.get("market_wide_share", 0) > 0.5:
        txt += (f" Note that {attribution['market_wide_share']:.0%} of this "
                f"reading comes from market-wide conditions shared by all "
                f"stocks, not from anything specific to this one.")
    return txt


def _sec_model_view(inp):
    t6 = inp["t6"]
    if _is_suppressed(inp):
        r = inp["reliability"]
        return (f"FORECAST WITHHELD. Over the last {r['t6_n']} matured "
                f"forecasts on this stock the model was directionally right "
                f"{_pct(r['t6_accuracy'], 1)} of the time, while always "
                f"guessing this stock's most common outcome "
                f"({r.get('t6_baseline_class')}) would have scored "
                f"{_pct(r['t6_baseline'], 1)}. Because the model is currently "
                f"worse than that naive rule here, its directional call is not "
                f"shown. The raw prediction is retained in the audit record "
                f"and the forecast returns automatically once the track "
                f"record recovers.")
    cls = t6["predicted_class"]
    verb = {"bullish": "a rise", "bearish": "a decline",
            "neutral": "no significant move"}[cls]
    probs = t6.get("probabilities") or {}
    band = inp["thresholds"]["t6_three_day"]

    # Target variable + horizon defined inline (FINRA 2214-style disclosure).
    txt = (f"Forecast target: the 3-trading-day close-to-close return, "
           f"classed bullish above +{band:.2f}%, bearish below -{band:.2f}%, "
           f"neutral between. The model reads {verb} as most likely. Full "
           f"probability estimate: bullish {_fmt_prob(probs.get('bullish'))}, "
           f"neutral {_fmt_prob(probs.get('neutral'))}, "
           f"bearish {_fmt_prob(probs.get('bearish'))}. ")
    if (t6.get("probability") or 0) >= 0.95:
        txt += ("A probability this extreme should be read with skepticism: "
                "in live use the model's very high probabilities have been "
                "right far less often than they claim. ")
    since = t6.get("champion_since")
    served = ("serving since deployment" if since == "initial"
              else f"serving since {since}")
    txt += (f"This forecast comes from the {t6['champion_model']} model "
            f"({served}), re-generated daily and re-evaluated for champion "
            f"status weekly.")
    return txt


def _sec_key_evidence(inp, attribution=None):
    """
    The specific rules that fired, with their fitted weights and source.

    Taken from the rule layer's own output (llm_analyses_audit.features_result),
    not from the Task 5 LLM's key_drivers. On 19 Sep the validator (R5) caught
    the LLM-written driver sentences carrying figures that exist nowhere in the
    report input (a computed "31%", SHAP values), and mixing SHAP magnitudes
    into the rule-weight column (e.g. 0.978). Deterministic rule output has
    neither problem: every number printed here is a stored rule weight.
    """
    feats = (attribution or {}).get("features") or []
    if not feats:
        return ("The rule-level breakdown for this date is not available in "
                "the audit record, so no itemised evidence is shown.")

    lines = ["Each line is one rule that fired today. The weight is its "
             "fitted contribution after market-wide discounting; a longer bar "
             "means more influence on the reading. Rules marked * were "
             "decisive: without them the reading would change."]
    for side, label in (("bullish", "Pointing up:"), ("bearish", "Pointing down:")):
        rows = sorted((f for f in feats if f["direction"] == side),
                      key=lambda f: -f["weight"])
        if not rows:
            continue
        lines.append("")
        lines.append(label)
        for f in rows:
            bar = "\u2588" * max(1, int(round(f["weight"] * 20)))
            src = _SOURCE_LABEL.get(f["source"], f["source"])
            star = "*" if f["decisive"] else " "
            lines.append(f"  {f['weight']:.3f} {bar:<18}{star} {f['factor']} "
                         f"[{src}]")
    net = (attribution or {}).get("net_score")
    if net is not None:
        lines.append("")
        lines.append(f"Net score {net:+.3f} against a decision line of "
                     f"\u00b10.35 (above +0.35 reads positive, below -0.35 "
                     f"negative, otherwise no clear lean).")
    nc = inp["t5"].get("n_contradictions")
    if nc is not None:
        lines.append(f"The system logged {nc} internal contradiction(s) "
                     f"between its components for this stock today.")
    return "\n".join(lines)


def _sec_what_happened(inp):
    a = inp["actual"]
    price = inp.get("price_context") or {}
    same_day = (f"On {inp['report_date']} the stock moved {price['return_pct']:+.2f}% "
                f"close-to-close, {price['relative_pct']:+.2f} percentage points "
                f"relative to the covered group's equal-weight average. "
                if price.get("as_of") == inp['report_date'] else
                "Same-date closing-price context is unavailable. ")
    if not a["matured"]:
        return (same_day + "The three-day outcome for this date is not yet known; this "
                "section will be complete once prices mature.")
    r = a["return_3d"]
    direction = {"bullish": "rose", "bearish": "fell", "neutral": "stayed roughly flat"}[a["class"]]
    return (same_day + f"Over the following three trading days the stock {direction} "
            f"({r:+.2f}%), which counts as {a['class']} under the system's "
            f"±{T6_THRESHOLD_DEFAULT:.2f}% band.")


def _sec_how_these_fit(inp):
    f = inp["fusion"]
    if _is_suppressed(inp):
        a = inp["actual"]
        if not a["matured"]:
            return ("With the forecast withheld, only the signal reading is "
                    "available for this stock today; there is no model view to "
                    "compare it with, and the price outcome is not yet known.")
        agree = a["class"] == inp["t5"]["sentiment"]
        return ("With the forecast withheld, the comparison here is between "
                "the signal reading and the price alone. "
                + ("They agreed. " if agree else
                   "They disagreed. Disagreement of this kind is common: the "
                   "information may already be in the price, or market-wide "
                   "movement may have outweighed stock-specific signals. This "
                   "system cannot determine which of these applies here. ")
                + "One day's agreement or disagreement is not evidence of "
                  "reliability either way.")
    txt = f["headline"] + ". " + f["note"]
    if f["archetype"] == "model_only":
        txt += (" The model may be responding to technical, macro or options "
                "patterns that do not appear in news coverage — or it may be "
                "reading noise. At the current track record it is not possible "
                "to determine which, so this view deserves curiosity rather "
                "than conviction.")
    elif f["archetype"] in DIVERGENCE_ARCHETYPES:
        txt += (" Disagreement of this kind is common and has several possible "
                "explanations: the information may already be reflected in the "
                "price, market-wide movement may be overwhelming stock-specific "
                "signals, or the tone of coverage may not reflect what matters "
                "to investors. This system cannot determine which of these "
                "applies here.")
    return txt


def _sec_reliability(inp):
    r = inp["reliability"]
    v = r["verdict"]
    sysr = r.get("system") or {}

    sys_txt = ""
    if sysr.get("n"):
        sys_txt = (f" Across all 15 covered stocks over the last 30 days, the "
                   f"deployed model's live record stands at {_pct(sysr.get('accuracy'), 1)} "
                   f"directional accuracy over {sysr['n']} matured forecasts. "
                   f"These are out-of-sample daily predictions as they were "
                   f"stored, not a backtest.")

    if v == "insufficient" and _is_suppressed(inp):
        # The forecast section already quotes the early record to explain the
        # withholding; say plainly that it is early rather than contradict it.
        return (f"Only {r.get('t6_n', 0)} matured forecasts exist on this stock, "
                f"fewer than the 15 needed to publish a per-stock accuracy "
                f"figure as a track record. The early record quoted above "
                f"({_pct(r.get('t6_accuracy'), 1)} right against "
                f"{_pct(r.get('t6_baseline'), 1)} for the naive rule) is shown "
                f"only to explain why the forecast is withheld; treat any view "
                f"on this stock with caution.{sys_txt}")
    if v == "insufficient":
        return (f"There is not enough history on this stock to quote a "
                f"per-stock hit rate ({r.get('t6_n', 0)} matured forecasts so "
                f"far; per-stock accuracy is withheld until 15 exist, so no "
                f"unsubstantiated statistic is quoted). Until then the "
                f"per-stock reading carries limited weight.{sys_txt}")
    acc  = r.get("t6_accuracy")
    base = r.get("t6_baseline")
    if base is not None:
        txt = (f"Within the trailing {r.get('window_days', 30)} calendar days "
               f"ending {inp['report_date']}, over {r.get('t6_n')} matured "
               f"champion forecasts on this stock "
               f"the model was directionally right {_pct(acc, 1)} of the time. "
               f"A time-ordered majority rule, chosen for each date using "
               f"only labels matured before that date (neutral with no history), "
               f"would have scored {_pct(base, 1)}.")
    else:
        txt = ("There is not yet a per-stock majority-class benchmark on "
               "the available matured predictions; reliability is insufficient.")
    if v == "below":
        txt += (" The model is below that naive rule, so its view carries "
                "limited weight and is best treated as context, not signal.")
    elif v == "marginal":
        txt += (" The model is no better than that naive rule, so weigh its "
                "view lightly.")
    else:
        txt += (" The model beats that naive rule, though still far from "
                "certainty.")
    txt += sys_txt
    if r.get("t5_coherence") is not None:
        txt += (f" Separately, the signal reading's direction matched the "
                f"realised 3-day move {_pct(r['t5_coherence'], 0)} of the time "
                f"on this stock.")
    return txt


def _sec_what_would_change(inp):
    t5s = inp["t5"]["sentiment"]
    if _is_suppressed(inp):
        lean = ("move off neutral with a clear shift in news tone, technical "
                "momentum or macro conditions" if t5s == "neutral" else
                "move toward neutral if the current signal mix reverses")
        return (f"The signal reading would {lean}. The withheld forecast is "
                f"re-checked daily and is shown again once the model's recent "
                f"hit rate on this stock beats its naive rule.")
    if inp["fusion"]["archetype"] == "model_only":
        return ("Two things to watch: whether tomorrow's signal reading "
                "starts leaning the same way the model does (which would "
                "strengthen the case), and whether the model's view persists "
                "when it re-runs on fresh data (a one-day view that vanishes "
                "was probably noise).")
    if t5s == "neutral":
        return ("A clear shift in news tone, technical momentum or macro "
                "conditions would move this reading off neutral at the next "
                "daily run.")
    side = "positive" if t5s == "bullish" else "negative"
    return (f"This reading depends on the {side} signal mix holding. A "
            f"reversal in news tone or technical momentum would likely move "
            f"the reading toward neutral at the next daily run; the model's "
            f"forecast is re-generated every day with fresh data.")


def _s2(v):
    """Signed two-decimal percent text without a '-0.00'."""
    return f"{0.0 if abs(v) < 0.005 else v:+.2f}"


def _sec_price_history(inp):
    """Price-history context (fb_v4). Every figure comes from
    inp['price_context'], computed from adjusted closes up to the report date.
    Descriptive: historical averages over many days, never a forecast."""
    pc = inp.get("price_context")
    if not pc:
        return ("Price history is unavailable for this report, so no "
                "historical comparison is shown.")
    tkr = inp["ticker"]
    verb = "rose" if pc["return_pct"] > 0 else "fell" if pc["return_pct"] < 0 else "was unchanged"
    amt = f" {abs(pc['return_pct']):.2f}%" if pc["return_pct"] != 0 else ""
    out = [
        f"On {pc['as_of']}, {tkr} {verb}{amt} while the {pc['n_stocks']} "
        f"covered stocks averaged {_s2(pc['group_return_pct'])}%. Its move "
        f"relative to the group was {_s2(pc['relative_pct'])}%, ranking "
        f"{pc['rank']} of {pc['n_stocks']}, which is in the {pc['band']} of "
        f"its own daily relative moves since {pc['group']['history_start']}."
    ]
    sb = pc["stock_after_band"]
    if sb.get("n"):
        txt = (f"On the {sb['n']} earlier days in that same band, {tkr}'s "
               f"next-day return relative to the group averaged "
               f"{_s2(sb['mean_next_rel_pct'])}%, and it outperformed the group "
               f"on {sb['share_outperformed']:.0%} of them")
        if sb.get("t") is not None and abs(sb["t"]) >= 2:
            txt += (f"; on this stock alone that tendency is distinguishable "
                    f"from chance (t {sb['t']:.1f}).")
        else:
            txt += "; on this stock alone that is too weak to tell apart from chance."
        out.append(txt)
    gb = pc["group_after_band"]
    if gb.get("n"):
        out.append(f"Across all covered stocks, days in this band were followed "
                   f"by an average next-day relative return of "
                   f"{_s2(gb['mean_next_rel_pct'])}% ({gb['share_outperformed']:.0%} "
                   f"outperformed, {gb['n']} stock-days).")
    g = pc["group"]
    rev_sig = (g.get("reversal_ic") is not None and g.get("reversal_ic_t") is not None
               and g["reversal_ic"] > 0 and g["reversal_ic_t"] >= 2)
    if g.get("reversal_ic") is not None and g.get("reversal_ic_t") is not None:
        if rev_sig:
            out.append(f"The group-wide pattern: over {g['reversal_days']} trading "
                       f"days, ranking the stocks in reverse order of their daily "
                       f"relative move has had an average rank correlation of "
                       f"{g['reversal_ic']:+.3f} with the next day's relative "
                       f"return (t {g['reversal_ic_t']:.1f}). Short-term relative "
                       f"moves in this group have tended to partly reverse the "
                       f"next day; the effect is small for any single day.")
        else:
            out.append(f"Across {g['reversal_days']} trading days there is no "
                       f"reliable group-wide tendency for daily relative moves to "
                       f"reverse or continue (rank correlation "
                       f"{g['reversal_ic']:+.3f}, t {g['reversal_ic_t']:.1f}).")
    # link to today's evidence reading when they point the same way as a move
    t5s = (inp.get("t5") or {}).get("sentiment")
    if rev_sig and ((t5s == "bullish" and pc["band_index"] == 4) or
                    (t5s == "bearish" and pc["band_index"] == 0)):
        out.append(f"Note: today's {t5s} signal reading coincides with a "
                   f"{pc['band']} relative move. Historically in this group, "
                   f"moves of that size have more often partly reversed than "
                   f"continued the next day, so the reading describes what "
                   f"happened more than what tends to follow.")
    m = pc.get("momentum") or {}
    if m.get("rank") is not None and g.get("momentum_ic") is not None:
        mt = g.get("momentum_ic_t")
        link = ("has been modestly positively related to"
                if (mt is not None and g["momentum_ic"] > 0 and mt >= 2)
                else "has not been reliably related to")
        out.append(f"Longer trend: {tkr}'s return over the {m['window_days']} "
                   f"trading days ending {m['skip_days']} days ago was "
                   f"{m['return_pct']:+.1f}%, ranking {m['rank']} of "
                   f"{pc['n_stocks']}. In this group that ranking {link} the "
                   f"following {m['horizon_days']}-day relative return "
                   f"(rank correlation {g['momentum_ic']:+.3f}"
                   + (f", t {mt:.1f})." if mt is not None else ")."))
    out.append("These are historical averages on dividend-adjusted closing "
               "prices, before trading costs, for today's list of covered "
               "stocks (which flatters the past, since stocks that dropped out "
               "are not included). They describe tendencies over many days, "
               "not a statement about this stock's next day.")
    return " ".join(out[:1]) + "\n" + "\n".join(out[1:])


def _sec_methodology(inp, attribution):
    """FINRA 2214-style block: methodology, assumptions, limitations."""
    rl = (attribution or {}).get("rule_layer_version") or "current"
    mws = (attribution or {}).get("market_wide_share")
    lines = [
        "Method: signals from four public sources (company news sentiment, "
        "technical indicators, macro conditions, options positioning) are "
        "scored by an evidence layer whose weights were fitted by ridge "
        "regression on next-day returns over a fixed historical window that "
        "predates every reported date; a separate classifier (the weekly "
        "champion among logistic regression, random forest and XGBoost, "
        "trained on 3-day returns and selected on live walk-forward F1) "
        "produces the forecast. Analyses regenerate daily "
        "after market close. The price-history section uses dividend-adjusted "
        "daily closes from Yahoo Finance, measures each stock's move relative "
        "to the equal-weighted average of the covered stocks, and only pairs "
        "days whose next-day outcome was known by the report date.",
        f"Versions: evidence rule layer {rl}; renderer "
        f"{PROMPT_VERSION_FALLBACK}; forecast champion as named above. All "
        "inputs, weights and outputs are stored with these versions for "
        "audit.",
        "Known limitations: the operating history is short, so all accuracy "
        "figures carry wide uncertainty; probability calibration is "
        "unreliable near the extremes; "
        + ("the evidence layer has a measured bullish tilt, mainly because its "
           "corporate-event rule fires on almost every day (routine earnings "
           "and dividend headlines) and has no equally frequent bearish "
           "counterpart; "
           if rl == "rl_v7" else "")
        + "market-wide conditions enter every stock's reading"
        + (f" (they contribute {mws:.0%} of this reading's weight)"
           if mws is not None else "")
        + "; confirmation is checked against 3-day outcomes even though the "
        "evidence layer is next-day-oriented, a horizon mismatch that a "
        "daily-return source will remove.",
    ]
    return "\n".join(lines)


